import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { test } from 'node:test';
import { isSynthetic } from '../../_shared/fhir/tags.mjs';
import { buildTicket, chartContext, LABELS, loadPack, tripwire } from '../lib/tripwire.mjs';

const { patients, notes } = loadPack();

test('P3 pack is regenerated byte for byte from its seed', () => {
  const out = execFileSync(
    process.execPath,
    [new URL('../../_shared/data-packs/p3-phi-like/generate.mjs', import.meta.url).pathname, '--check'],
    { encoding: 'utf8' }
  );
  assert.match(out, /^PASS/);
});

test('every P3 patient is tagged synthetic and uses only fictional identifier ranges', () => {
  for (const p of patients.values()) {
    assert.ok(isSynthetic(p), p.id);
    const ids = Object.fromEntries(p.identifier.map((i) => [i.system, i.value]));
    assert.match(ids['https://foomedical.example/mrn'], /^HTEST-MRN-\d{5}$/);
    assert.match(ids['http://hl7.org/fhir/sid/us-ssn'], /^9\d{2}-/);
    assert.match(p.telecom[0].value, /555-01\d{2}$/);
    assert.match(p.telecom[1].value, /@example\.(com|org|net)$/);
  }
});

test('planted span offsets match the note text', () => {
  for (const n of notes) {
    for (const s of n.spans) {
      assert.equal(n.text.slice(s.start, s.end), s.value, `${n.id} ${s.type}`);
    }
  }
});

test('with chart context a note is allowed and its ticket holds none of the planted values', () => {
  const n = notes[0];
  const r = tripwire(n.text, { known: chartContext(patients.get(n.patient)) });
  assert.equal(r.allowed, true);
  assert.ok(r.rawHits.length > 0);
  const ticket = buildTicket(n.id, r);
  assert.deepEqual(ticket.fields.labels, LABELS);
  for (const s of n.spans) {
    assert.ok(!JSON.stringify(ticket).includes(s.value), `${s.type} ${s.value}`);
  }
});

test('an identifier the patterns do not know blocks the write', () => {
  const r = tripwire('Account 65897152, call back later.', { known: ['Someone Else'] });
  assert.equal(r.allowed, false);
  assert.deepEqual(r.blocked, ['DIGITS']);
});

test('without chart context nothing is written, even when the screens look clean', () => {
  const n = notes.find((x) => x.text.startsWith('Okonkwo, James'));
  const r = tripwire(n.text);
  assert.ok(r.redacted.includes('Okonkwo'), 'blind redaction misses this name, which is why the rule exists');
  assert.equal(r.allowed, false);
  assert.ok(r.blocked.includes('NO_CHART_CONTEXT'));
});
